#!/usr/bin/env python3
"""Complete base-multigraph classification and exact symbolic D3 capacity.

No voltage assignment, lifted graph, or BFS is generated by this program.
Each loop has two distinct darts, and only the immediately inverse dart is
forbidden. Equality of endpoint forms is checked both before and after gauge.
"""
import itertools
import json
import time
from collections import Counter
from pathlib import Path

OUT = Path(__file__).resolve().parent
PAIRS = list(itertools.combinations(range(4), 2))
PERMS = list(itertools.permutations(range(4)))
START = time.process_time()
WALL = time.monotonic()
CPU_LIMIT = 27.0
DEGREE = 6
FIBER = 31
EDGES = 12


def matrix(key):
    a = [[0] * 4 for _ in range(4)]
    for (i, j), m in zip(PAIRS, key[4:]):
        a[i][j] = a[j][i] = m
    return a


def images(key):
    a = matrix(key)
    return {tuple(key[p[i]] for i in range(4)) +
            tuple(a[p[i]][p[j]] for i, j in PAIRS) for p in PERMS}


def connected(key):
    a = matrix(key)
    reached = {0}
    stack = [0]
    while stack:
        i = stack.pop()
        for j in range(4):
            if a[i][j] and j not in reached:
                reached.add(j)
                stack.append(j)
    return len(reached) == 4


def enumerate_bases():
    canonical = Counter()
    counts = Counter()
    for loops in itertools.product(range(DEGREE // 2 + 1), repeat=4):
        r = [DEGREE - 2 * x for x in loops]
        half = (r[0] + r[1] + r[2] - r[3]) // 2
        for a in range(min(r[0], r[1]) + 1):
            for b in range(min(r[0] - a, r[2]) + 1):
                c = half - a - b
                cross = (a, b, r[0] - a - b, c, r[1] - a - c,
                         r[2] - b - c)
                if min(cross) < 0:
                    continue
                key = loops + cross
                mat = matrix(key)
                assert all(2 * key[i] + sum(mat[i]) == DEGREE for i in range(4))
                counts['labeled_degree_valid'] += 1
                if not connected(key):
                    counts['labeled_disconnected'] += 1
                    continue
                counts['labeled_connected'] += 1
                canonical[min(images(key))] += 1
    for key, multiplicity in canonical.items():
        assert len(images(key)) == multiplicity
    counts['unlabeled_connected'] = len(canonical)
    counts['connected_with_loops'] = sum(sum(k[:4]) > 0 for k in canonical)
    counts['connected_without_loops'] = sum(sum(k[:4]) == 0 for k in canonical)
    return canonical, dict(counts)


def topology(key):
    edges = []
    for i, count in enumerate(key[:4]):
        edges.extend([(i, i)] * count)
    for pair, count in zip(PAIRS, key[4:]):
        edges.extend([pair] * count)
    assert len(edges) == EDGES
    parent = list(range(4))
    def root(i):
        while parent[i] != i:
            i = parent[i]
        return i
    tree = []
    for eid, (u, v) in enumerate(edges):
        ru, rv = root(u), root(v)
        if ru != rv:
            parent[ru] = rv
            tree.append(eid)
    assert len(tree) == 3 and all(edges[t][0] != edges[t][1] for t in tree)
    return edges, tree


def capacity(key):
    edges, tree = topology(key)
    free = [e for e in range(EDGES) if e not in tree]
    adjacency = [[] for _ in range(4)]
    for eid, (u, v) in enumerate(edges):
        adjacency[u].append((2 * eid, v, eid, 1))
        adjacency[v].append((2 * eid + 1, u, eid, -1))
    assert all(len(a) == DEGREE for a in adjacency)
    raw_counts, distinct, gauge_distinct = [], [], []
    depth_counts = []
    for source in range(4):
        forms = [set() for _ in range(4)]
        gauged = [set() for _ in range(4)]
        raw = [0] * 4
        depths = [0] * 4
        coeff = [0] * EDGES
        def visit(v, remaining, last_dart):
            raw[v] += 1
            depths[3 - remaining] += 1
            forms[v].add(tuple(x % FIBER for x in coeff))
            gauged[v].add(tuple(coeff[e] % FIBER for e in free))
            if remaining:
                for dart, w, eid, sign in adjacency[v]:
                    if last_dart >= 0 and dart == (last_dart ^ 1):
                        continue
                    coeff[eid] += sign
                    visit(w, remaining - 1, dart)
                    coeff[eid] -= sign
        visit(source, 3, -1)
        assert depths == [1, DEGREE, DEGREE*(DEGREE-1), DEGREE*(DEGREE-1)**2]
        sizes = [len(f) for f in forms]
        gsizes = [len(f) for f in gauged]
        assert sizes == gsizes
        raw_counts.append(raw)
        depth_counts.append(depths)
        distinct.append(sizes)
        gauge_distinct.append(gsizes)
    assert all(distinct[i][j] == distinct[j][i] for i in range(4) for j in range(4))
    flat = sum(distinct, [])
    return {
        'loops': list(key[:4]), 'cross_pairs_order': [list(p) for p in PAIRS],
        'cross_multiplicities': list(key[4:]), 'cross_matrix': matrix(key),
        'edge_u': [e[0] for e in edges], 'edge_v': [e[1] for e in edges],
        'tree_edge_indices': tree, 'free_edge_indices': free,
        'raw_walk_counts': raw_counts, 'walk_counts_by_length': depth_counts,
        'capacity_by_root_target': distinct,
        'gauged_capacity_by_root_target': gauge_distinct,
        'minimum_capacity': min(flat), 'total_capacity': sum(flat),
        'forced_ordered_representative_misses_lower_bound': sum(max(0, FIBER-v) for v in flat),
        'capacity_pass': min(flat) >= FIBER,
    }


def main():
    bases, counts = enumerate_bases()
    enumeration_cpu = time.process_time() - START
    keys = sorted(bases)
    records = []
    output = OUT / 'all_bases.jsonl'
    with output.open('w') as stream:
        for index, key in enumerate(keys):
            if time.process_time() - START >= CPU_LIMIT:
                break
            rec = capacity(key)
            rec.update({'id': index, 'canonical_key': list(key),
                        'labeled_orbit_size': bases[key], 'vertex_automorphism_count': 24 // bases[key]})
            records.append(rec)
            stream.write(json.dumps(rec, separators=(',', ':')) + '\n')
            if (index + 1) % 25 == 0:
                stream.flush()
                (OUT / 'progress.json').write_text(json.dumps({
                    'completed_bases': index + 1, 'total_bases': len(keys),
                    'CPU_seconds': time.process_time() - START,
                    'capacity_pass_count': sum(r['capacity_pass'] for r in records)}, indent=2) + '\n')
    complete = len(records) == len(keys)
    survivors = [r for r in records if r['capacity_pass']]
    ranking = sorted(records, key=lambda r: (-r['minimum_capacity'], -r['total_capacity'], r['canonical_key']))
    loop_ranking = [r for r in ranking if sum(r['loops']) > 0]
    balance_key = min(images((0,0,0,0,2,2,2,2,2,2)))
    balanced = next((r for r in records if tuple(r['canonical_key']) == balance_key), None)
    by_loops = []
    for loops in sorted({sum(r['loops']) for r in records}):
        rr = [r for r in records if sum(r['loops']) == loops]
        by_loops.append({'total_loops': loops, 'bases': len(rr),
                         'capacity_pass': sum(r['capacity_pass'] for r in rr),
                         'max_minimum_capacity': max(r['minimum_capacity'] for r in rr)})
    for name, value in [('survivors.json', survivors), ('top_bases.json', ranking[:12]),
                        ('top_loop_bases.json', loop_ranking[:12])]:
        (OUT / name).write_text(json.dumps(value, indent=2) + '\n')
    summary = {
        'status': 'COMPLETE' if complete else 'CPU_LIMIT_PREFIX_SAVED', 'running': False,
        'task': 'complete C31 voltage-base symbolic capacity; no voltage search',
        'degree': DEGREE, 'orbits': 4, 'fiber_order': FIBER, 'diameter_target': 3,
        'classification_counts': counts, 'bases_completed': len(records), 'next_base_index': len(records),
        'capacity_pass_count': len(survivors),
        'capacity_pass_with_loops': sum(sum(r['loops']) > 0 for r in survivors),
        'capacity_pass_without_loops': sum(sum(r['loops']) == 0 for r in survivors),
        'by_total_loops': by_loops,
        'minimum_capacity_histogram': dict(sorted(Counter(r['minimum_capacity'] for r in records).items())),
        'balanced_222': balanced, 'best': ranking[0] if ranking else None,
        'best_with_loops': loop_ranking[0] if loop_ranking else None,
        'raw_vs_tree_gauge_equal_for_every_completed_slot': True,
        'evaluated_voltage_assignments': 0, 'generated_lifted_graphs': 0, 'BFS_roots': 0,
        'enumeration_CPU_seconds': enumeration_cpu,
        'CPU_seconds': time.process_time() - START, 'wall_seconds': time.monotonic() - WALL,
    }
    (OUT / 'results.json').write_text(json.dumps(summary, indent=2) + '\n')
    (OUT / 'terminal.json').write_text(json.dumps({k: summary[k] for k in [
        'status', 'running', 'bases_completed', 'next_base_index', 'capacity_pass_count',
        'evaluated_voltage_assignments', 'generated_lifted_graphs', 'BFS_roots',
        'CPU_seconds', 'wall_seconds']}, indent=2) + '\n')
    print(json.dumps({k: summary[k] for k in ['status','classification_counts','bases_completed',
        'capacity_pass_count','capacity_pass_with_loops','by_total_loops','CPU_seconds','wall_seconds']}, indent=2))


if __name__ == '__main__':
    main()
