"""Independent complete (p6,z8,w8), lambda(z,w)=3 entry and fixed-certificate audit."""
from pathlib import Path
from itertools import product, combinations
from fractions import Fraction
import json, time
from replay import verify
HERE = Path(__file__).parent

def signature(r):
    return (tuple(r['neighbor_codegrees']), tuple(tuple(b) for b in r['center_partition']), r['neighbor_triple'], tuple(int(r['counts'].get(str(m), r['counts'].get(m, 0))) for m in range(16)))

def main():
    start = time.time()
    pilot = json.loads((HERE/'PILOT.json').read_text())['triples']
    gate = {(tuple(r['degrees'][1:]), r['codegrees'][2], r['triple']): r['strict'] for r in pilot}
    # All set partitions of three original labels, generated by restricted growth strings.
    partitions = []
    for labels in product(range(3), repeat=3):
        if labels[0] or any(labels[i] > 1 + max(labels[:i]) for i in (1, 2)):
            continue
        partitions.append(tuple(tuple(i for i in range(3) if labels[i] == b) for b in range(max(labels)+1)))
    generated = []
    for a, b in product(range(1, 7), repeat=2):
        if a + b - 2 > 4:  # actual p degree6 codegree excess4
            continue
        for pp in partitions:
            same = lambda ij: int(any(set(ij) <= set(B) for B in pp))
            if gate[((6, 8), a, same((0, 1)))] or gate[((6, 8), b, same((0, 2)))] or gate[((8, 8), 3, same((1, 2)))]:
                continue
            for t in range(min(a, b, 3)+1):
                inclusive = {1:6, 2:8, 4:8, 3:a, 5:b, 6:3, 7:t}
                outside_inc = {m: inclusive[m] - int(any(all(i in B for i in range(3) if m>>i&1) for B in pp)) for m in inclusive}
                exact = {m: sum((-1)**(u.bit_count()-m.bit_count())*outside_inc[u] for u in inclusive if u&m == m) for m in inclusive}
                exact[0] = 30 - sum(exact.values())
                counts = {m<<1:n for m,n in exact.items()}
                counts[1] = 5-len(pp)
                for B in pp:
                    counts[1|sum(1<<(i+1) for i in B)] = 1
                if min(counts.values()) >= 0:
                    generated.append(dict(neighbor_codegrees=[a,b,3], center_partition=pp, neighbor_triple=t, counts=counts))
    original_domain = json.loads((HERE/'STAR_LOW_DOMAIN.json').read_text())['cases']
    original_dp = json.loads((HERE/'STAR_LOW_DP.json').read_text())['cases']
    domain_ids = [i for i,r in enumerate(original_domain) if r['neighbor_degrees'] == [6,8,8] and r['neighbor_codegrees'][2] == 3]
    dp_ids = [i for i,r in enumerate(original_dp) if r['neighbor_degrees'] == [6,8,8] and r['neighbor_codegrees'][2] == 3]
    assert len(generated) == len(domain_ids) == len(dp_ids) == 11
    assert {signature(r) for r in generated} == {signature(original_domain[i]) for i in domain_ids} == {signature(original_dp[i]) for i in dp_ids}
    rows = []
    for i in dp_ids:
        r = original_dp[i]
        value = verify(r)  # independent expanded35-stub injection and nested quota replay
        assert value < 1 and r['strict']
        rows.append(dict(source_index_zero_based=i, neighbor_codegrees=r['neighbor_codegrees'], center_partition=r['center_partition'], neighbor_triple=r['neighbor_triple'], positions=r['positions'], bound=str(value), counts=r['counts']))
    all688 = [r for r in original_dp if r['neighbor_degrees'] == [6,8,8]]
    residual = [r for r in all688 if not r['strict']]
    assert len(all688)==59 and len(residual)==16 and all(max(r['neighbor_codegrees'])<=2 for r in residual)
    result = dict(status='PASS', scope=__doc__, independent_domain_cases=11, fixed_certificate_cases=11, independent_rows=231, max_bound=str(max(Fraction(r['bound']) for r in rows)), complete688_domain=59, complete688_residual=16, residual_pair_codegrees_at_most2=True, rows=rows, elapsed_seconds=time.time()-start)
    (HERE/'C3_ENTRY_AUDIT.json').write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps(result, ensure_ascii=False, indent=2))
if __name__ == '__main__':
    main()
