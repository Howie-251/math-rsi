"""Independent exact replay: old86 top-distinct-pair bound and M2=7/8.

Only five positive-label multigraphs are enumerated, never hypergraphs H.
New labels are generated by assigning one entire forward vertex star at a time.
"""
from collections import Counter
from itertools import combinations, permutations, product
from math import comb
from pathlib import Path
import json
import time

HERE=Path(__file__).resolve().parent
PAIRS=tuple(combinations(range(5),2))
PAIR_INDEX={e:i for i,e in enumerate(PAIRS)}
DISJOINT=tuple((i,j) for i,e in enumerate(PAIRS)
               for j,f in enumerate(PAIRS) if i<j and not set(e)&set(f))

def matching_count(g):
    return sum(g[i]*g[j] for i,j in DISJOINT)

def reconstruct(g):
    masks=[]
    degrees=[0]*5
    for (u,v),multiplicity in zip(PAIRS,g):
        masks.extend([(1<<u)|(1<<v)]*multiplicity)
        degrees[u]+=multiplicity
        degrees[v]+=multiplicity
    assert max(degrees)<=4
    for u,d in enumerate(degrees):
        masks.extend([1<<u]*(4-d))
    assert all(sum(bool(mask&(1<<u)) for mask in masks)==4 for u in range(5))
    return masks

def direct_candidates(masks,k):
    out=[]
    for ids in combinations(range(len(masks)),k):
        covered=0
        for i in ids:covered |= masks[i]
        if covered==31:out.append(ids)
    return out

def inclusion_exclusion(masks,k):
    value=0
    for labels in range(32):
        unhit=sum(not (mask&labels) for mask in masks)
        value+=(-1)**labels.bit_count()*(comb(unhit,k) if unhit>=k else 0)
    return value

def top_pair_replay():
    source=HERE.parents[1]/'twentyfour/positive_occ_three/five_graph_catalogue.json'
    old=json.loads(source.read_text())
    rows=[]
    for row in old['graphs']:
        g=tuple(row['edge_vector'])
        masks=reconstruct(g)
        candidates=direct_candidates(masks,4)
        assert len(candidates)==inclusion_exclusion(masks,4)==row['C4']
        pair=Counter()
        triple=Counter()
        for candidate in candidates:
            pair.update(combinations(candidate,2))
            triple.update(combinations(candidate,3))
        # Each key is a DISTINCT actual point-pair, including parallel-point labels.
        pair_counts=sorted(pair.values(),reverse=True)
        g3=max(triple.values(),default=0)
        possibilities=[]
        for r in range(5):
            top=sum(pair_counts[:r])
            for b in range(5-r):
                blocked=top+(4-r)*g3+b*g3+(17-b)
                possibilities.append({'r':r,'b':b,'top_distinct_pair_sum':top,
                                      'blocked_upper_bound':blocked})
        worst=max(possibilities,key=lambda z:z['blocked_upper_bound'])
        gap=len(candidates)-worst['blocked_upper_bound']
        assert gap>0,(row['index'],gap)
        rows.append({'old_orbit_id':row['index'],'edge_vector':g,
                     'E':sum(g),'M2':matching_count(g),'C4':len(candidates),
                     'top_four_distinct_pair_extensions':pair_counts[:4],
                     'maximum_triple_extension':g3,'worst_case':worst,
                     'margin':gap,'all_budget_cases':possibilities})
    assert len(rows)==86
    return {'old_orbits':len(rows),'old_labeled_graphs':old['labeled_graphs'],
            'minimum_margin':min(r['margin'] for r in rows),
            'minimum_margin_orbits':[r['old_orbit_id'] for r in rows
                                    if r['margin']==min(z['margin'] for z in rows)],
            'rows':rows}

def star_domain():
    """At vertex i assign all m_(i,j), j>i, as one whole star.

    Previously assigned entries fix its incoming degree. Each legal vector
    has one unique branch at each successive vertex. Partial M2 is monotone,
    so pruning it above8 cannot remove an M2=7 or8 vector.
    """
    g=[0]*10
    degrees=[0]*5
    answer=set()
    def recurse(i):
        if i==4:
            if matching_count(g) in (7,8):answer.add(tuple(g))
            return
        targets=list(range(i+1,5))
        indices=[PAIR_INDEX[i,j] for j in targets]
        available=4-degrees[i]
        ranges=[range(min(available,4-degrees[j])+1) for j in targets]
        for values in product(*ranges):
            if sum(values)>available:continue
            for j,k,value in zip(targets,indices,values):
                g[k]=value
                degrees[j]+=value
            if matching_count(g)<=8:recurse(i+1)
            for j,k,value in zip(targets,indices,values):
                g[k]=0
                degrees[j]-=value
    recurse(0)
    return answer

MAPS=[]
for permutation in permutations(range(5)):
    MAPS.append(tuple(PAIR_INDEX[tuple(sorted((permutation[u],permutation[v])))]
                      for u,v in PAIRS))

def transport(g,mapping):
    out=[0]*10
    for k,position in enumerate(mapping):out[position]=g[k]
    return tuple(out)

def new_domain_replay():
    domain=star_domain()
    assert sum(matching_count(g)==7 for g in domain)==1020
    assert sum(matching_count(g)==8 for g in domain)==1395
    # Count by two different formulas on EVERY labeled vector, not only reps.
    labeled=[]
    counts={}
    for g in sorted(domain):
        masks=reconstruct(g)
        direct=len(direct_candidates(masks,3))
        ie=inclusion_exclusion(masks,3)
        assert direct==ie
        counts[g]=direct
        labeled.append({'edge_vector':g,'M2':matching_count(g),'E':sum(g),
                        'union_size':len(masks),'C3_direct':direct,'C3_IE':ie})
    remaining=set(domain)
    representatives=[]
    while remaining:
        g=min(remaining)
        orbit={transport(g,mapping) for mapping in MAPS}
        assert orbit<=domain and all(counts[h]==counts[g] for h in orbit)
        representatives.append({'edge_vector':g,'M2':matching_count(g),
                                'orbit_size':len(orbit),'C3':counts[g]})
        remaining-=orbit
    assert sum(r['orbit_size'] for r in representatives)==len(domain)
    minima={str(m):min(counts[g] for g in domain if matching_count(g)==m) for m in (7,8)}
    assert minima=={'7':18,'8':21}
    return {'generation':'whole forward vertex stars; cap4; monotone M2<=8 only',
            'labeled_graphs':len(domain),'label_count_by_M2':{
                str(m):sum(matching_count(g)==m for g in domain) for m in (7,8)},
            'orbits':len(representatives),'orbit_count_by_M2':{
                str(m):sum(r['M2']==m for r in representatives) for m in (7,8)},
            'minimum_C3_by_M2':minima,'representatives':representatives,
            'all_labeled_vectors':labeled}

def main():
    start=time.perf_counter()
    old=top_pair_replay()
    split=time.perf_counter()
    new=new_domain_replay()
    result={'scope':__doc__,'old86_top_distinct_pair':old,'new_M2_7_8':new,
            'old86_seconds':split-start,'new_domain_seconds':time.perf_counter()-split,
            'status':'PASS'}
    (HERE/'REPLAY.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({'status':'PASS','old86_minimum_margin':old['minimum_margin'],
                      'old86_minimum_margin_orbits':old['minimum_margin_orbits'],
                      'new_labels':new['label_count_by_M2'],'new_orbits':new['orbit_count_by_M2'],
                      'new_C3_minima':new['minimum_C3_by_M2'],
                      'seconds':time.perf_counter()-start},indent=2))

if __name__=='__main__':main()
